-- Pruebas de relaciones generadas a partir del modelo de Power BI (una por relacion).
-- Cada dimension no repite su clave y cada hecho encuentra su dimension. Se espera 0 fallos.
USE SCHEMA DEMO_VIDEO.COMERCIO;
SELECT
    PRUEBA,
    FALLOS,
    IFF(FALLOS = 0, 'OK', 'FALLA') AS RESULTADO
FROM (
    SELECT
        'D_MES.MESNUM repetida' AS PRUEBA,
        COUNT(*) - COUNT(DISTINCT MESNUM) AS FALLOS
    FROM D_MES
    UNION ALL
    SELECT
        'D_LINEA.LINEAID repetida' AS PRUEBA,
        COUNT(*) - COUNT(DISTINCT LINEAID) AS FALLOS
    FROM D_LINEA
    UNION ALL
    SELECT
        'D_ARTICULO.ARTICULOID repetida' AS PRUEBA,
        COUNT(*) - COUNT(DISTINCT ARTICULOID) AS FALLOS
    FROM D_ARTICULO
    UNION ALL
    SELECT
        'D_TERRITORIO.TERRITORIOID repetida' AS PRUEBA,
        COUNT(*) - COUNT(DISTINCT TERRITORIOID) AS FALLOS
    FROM D_TERRITORIO
    UNION ALL
    SELECT
        'F_VENTAS.MESNUM sin D_MES' AS PRUEBA,
        COUNT(*) AS FALLOS
    FROM F_VENTAS AS F LEFT JOIN D_MES AS D ON F.MESNUM = D.MESNUM
    WHERE D.MESNUM IS NULL
    UNION ALL
    SELECT
        'F_VENTAS.LINEAID sin D_LINEA' AS PRUEBA,
        COUNT(*) AS FALLOS
    FROM F_VENTAS AS F LEFT JOIN D_LINEA AS D ON F.LINEAID = D.LINEAID
    WHERE D.LINEAID IS NULL
    UNION ALL
    SELECT
        'F_VENTAS.ARTICULOID sin D_ARTICULO' AS PRUEBA,
        COUNT(*) AS FALLOS
    FROM F_VENTAS AS F LEFT JOIN D_ARTICULO AS D ON F.ARTICULOID = D.ARTICULOID
    WHERE D.ARTICULOID IS NULL
    UNION ALL
    SELECT
        'F_VENTAS.TERRITORIOID sin D_TERRITORIO' AS PRUEBA,
        COUNT(*) AS FALLOS
    FROM F_VENTAS AS F LEFT JOIN D_TERRITORIO AS D ON F.TERRITORIOID = D.TERRITORIOID
    WHERE D.TERRITORIOID IS NULL
    UNION ALL
    SELECT
        'F_STOCK.MESNUM sin D_MES' AS PRUEBA,
        COUNT(*) AS FALLOS
    FROM F_STOCK AS F LEFT JOIN D_MES AS D ON F.MESNUM = D.MESNUM
    WHERE D.MESNUM IS NULL
    UNION ALL
    SELECT
        'F_STOCK.LINEAID sin D_LINEA' AS PRUEBA,
        COUNT(*) AS FALLOS
    FROM F_STOCK AS F LEFT JOIN D_LINEA AS D ON F.LINEAID = D.LINEAID
    WHERE D.LINEAID IS NULL
    UNION ALL
    SELECT
        'F_STOCK.ARTICULOID sin D_ARTICULO' AS PRUEBA,
        COUNT(*) AS FALLOS
    FROM F_STOCK AS F LEFT JOIN D_ARTICULO AS D ON F.ARTICULOID = D.ARTICULOID
    WHERE D.ARTICULOID IS NULL
    UNION ALL
    SELECT
        'F_COBERTURA.MESNUM sin D_MES' AS PRUEBA,
        COUNT(*) AS FALLOS
    FROM F_COBERTURA AS F LEFT JOIN D_MES AS D ON F.MESNUM = D.MESNUM
    WHERE D.MESNUM IS NULL
    UNION ALL
    SELECT
        'F_COBERTURA.ARTICULOID sin D_ARTICULO' AS PRUEBA,
        COUNT(*) AS FALLOS
    FROM F_COBERTURA AS F LEFT JOIN D_ARTICULO AS D ON F.ARTICULOID = D.ARTICULOID
    WHERE D.ARTICULOID IS NULL
) AS PRUEBAS
ORDER BY RESULTADO, PRUEBA;
